"""
build_mp20_three_property_lmdb.py
==================================
Builds data/mp20_three_property/{train,val,test}/data.lmdb from:
  - data/all_with_180.csv   (formation energy, band gap, CIF strings — 45k materials)
  - data/labels/mp20_bulk_modulus.csv   (generated by download_bulk_modulus.py)

Only structures present in BOTH files are included (intersection).

Properties stored per structure:
  y_eform    = formation_energy_per_atom  (eV/atom, raw)
  y_bandgap  = band_gap                   (eV, raw)
  y_gvrh     = k_vrh_log10               (log10 GPa, matches existing mp_gvrh convention)

Graph construction uses AtomsToGraphs with the same settings as the existing
mp_gvrh/mp_dielectric datasets (radius=12Å, max_neigh=20).

Run from the repo root:
    python scripts/build_lmdb/build_mp20_three_property_lmdb.py [--filter-stable]

    --filter-stable : only include structures with e_above_hull == 0
                      (recommended for inverse design; reduces set by ~30%)

After completion, copy the printed YAML block into:
    configs/mex-multi/mp20_three_property.yml
"""

import argparse
import csv
import logging
import os
import pickle
import sys
from pathlib import Path

import numpy as np
import lmdb
import torch
from torch_geometric.data import Data

logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")

REPO_ROOT = Path(__file__).resolve().parent.parent.parent  # scripts/build_lmdb/ -> repo root
os.chdir(REPO_ROOT)

CSV_ALL   = Path("data/all_with_180.csv")
CSV_GVRH  = Path("data/labels/mp20_bulk_modulus.csv")
OUT_ROOT  = Path("data/mp20_three_property")
SEED      = 42

# Graph construction settings — must match equiformer_v2 defaults
RADIUS     = 12.0
MAX_NEIGH  = 20


# ─────────────────────────────────────────────────────────────────────────────
# Dependency check
# ─────────────────────────────────────────────────────────────────────────────

def check_deps():
    missing = []
    for pkg in ["pymatgen", "ase", "lmdb", "torch"]:
        try:
            __import__(pkg)
        except ImportError:
            missing.append(pkg)
    if missing:
        print(f"ERROR: Missing packages: {missing}\nRun: pip install {' '.join(missing)}")
        sys.exit(1)


# ─────────────────────────────────────────────────────────────────────────────
# Read CSV files
# ─────────────────────────────────────────────────────────────────────────────

def read_bulk_modulus(path: Path) -> dict:
    """Return {material_id: k_vrh_log10}."""
    data = {}
    with open(path, newline="") as f:
        for row in csv.DictReader(f):
            mid = row["material_id"].strip()
            try:
                val = float(row["k_vrh_log10"])
                if not (val != val):  # skip NaN
                    data[mid] = val
            except (ValueError, KeyError):
                pass
    return data


def read_main_csv(path: Path, bulk_mod: dict, filter_stable: bool):
    """
    Read all_with_180.csv, keep only rows whose material_id is in bulk_mod.
    Returns list of dicts with keys: material_id, eform, bandgap, gvrh, cif
    """
    records = []
    seen = set()
    logging.info(f"Scanning {path} ...")
    with open(path, newline="") as f:
        reader = csv.DictReader(f)
        for i, row in enumerate(reader):
            mid = row.get("material_id", "").strip()
            if mid not in bulk_mod:
                continue
            if mid in seen:
                continue
            seen.add(mid)

            if filter_stable:
                try:
                    e_hull = float(row.get("e_above_hull", "999"))
                    if e_hull > 1e-6:
                        continue
                except ValueError:
                    continue

            try:
                eform   = float(row["formation_energy_per_atom"])
                bandgap = float(row["band_gap"])
                cif     = row["cif"].strip()
            except (ValueError, KeyError):
                continue

            if not cif:
                continue

            records.append({
                "material_id": mid,
                "eform":   eform,
                "bandgap": bandgap,
                "gvrh":    bulk_mod[mid],
                "cif":     cif,
            })

            if i % 500000 == 0 and i > 0:
                logging.info(f"  scanned {i:,} rows, kept {len(records):,} so far ...")

    return records


# ─────────────────────────────────────────────────────────────────────────────
# CIF → ASE Atoms → torch_geometric Data
# ─────────────────────────────────────────────────────────────────────────────

def cif_to_graph(cif_str: str, sid: int) -> Data:
    """Parse a CIF string directly to a torch_geometric Data object.
    Uses pymatgen for neighbor search — no torch_scatter required.
    """
    from pymatgen.core import Structure
    from pymatgen.io.ase import AseAtomsAdaptor

    struct = Structure.from_str(cif_str, fmt="cif")
    atoms  = AseAtomsAdaptor.get_atoms(struct)

    # Neighbor list via pymatgen (same as OCP's AtomsToGraphs._get_neighbors_pymatgen)
    _c_index, _n_index, _offsets, n_distance = struct.get_neighbor_list(
        r=RADIUS, numerical_tol=0, exclude_self=True
    )

    # Trim to MAX_NEIGH closest neighbors per center atom
    _nonmax_idx = []
    for i in range(len(atoms)):
        idx_i = (_c_index == i).nonzero()[0]
        idx_sorted = np.argsort(n_distance[idx_i])[:MAX_NEIGH]
        _nonmax_idx.append(idx_i[idx_sorted])
    _nonmax_idx = np.concatenate(_nonmax_idx)

    _c_index  = _c_index[_nonmax_idx]
    _n_index  = _n_index[_nonmax_idx]
    n_distance = n_distance[_nonmax_idx]
    _offsets  = _offsets[_nonmax_idx]

    edge_index    = torch.LongTensor(np.vstack((_n_index, _c_index)))
    cell_offsets  = torch.LongTensor(_offsets)
    edge_distances = torch.FloatTensor(n_distance)

    # Remove near-zero distances (pymatgen edge case)
    nonzero = torch.where(edge_distances >= 1e-8)[0]
    edge_index   = edge_index[:, nonzero]
    cell_offsets = cell_offsets[nonzero]

    natoms = len(atoms)
    tags   = torch.zeros(natoms, dtype=torch.long)
    fixed  = torch.zeros(natoms, dtype=torch.int)

    data = Data(
        cell=torch.tensor(np.array(atoms.get_cell()), dtype=torch.float).view(1, 3, 3),
        pos=torch.tensor(atoms.get_positions(), dtype=torch.float),
        atomic_numbers=torch.tensor(atoms.get_atomic_numbers(), dtype=torch.long),
        natoms=natoms,
        tags=tags,
        fixed=fixed,
        edge_index=edge_index,
        cell_offsets=cell_offsets,
        sid=torch.LongTensor([sid]),
    )
    return data


# ─────────────────────────────────────────────────────────────────────────────
# LMDB writer
# ─────────────────────────────────────────────────────────────────────────────

def write_lmdb(records, pool, idx_arr, split_name: str):
    out_dir  = OUT_ROOT / split_name
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / "data.lmdb"

    env = lmdb.open(str(out_path), map_size=2 * 1024**3, subdir=False)  # 2 GB
    natoms_list = []

    failed = 0
    with env.begin(write=True) as txn:
        new_i = 0
        for old_i in idx_arr:
            rec = records[old_i]
            try:
                data = cif_to_graph(rec["cif"], sid=new_i)
            except Exception as e:
                logging.warning(
                    f"  [{split_name}] {rec['material_id']} graph build failed: {e}"
                )
                failed += 1
                continue

            # Attach property targets
            data.y_eform   = float(rec["eform"])
            data.y_bandgap = float(rec["bandgap"])
            data.y_gvrh    = float(rec["gvrh"])
            data.material_id = rec["material_id"]

            txn.put(str(new_i).encode(), pickle.dumps(data))
            natoms_list.append(int(data.natoms))
            new_i += 1

            if new_i % 500 == 0:
                logging.info(f"  [{split_name}] written {new_i} ...")

        txn.put(b"length", pickle.dumps(new_i))

    env.close()

    # metadata.npz (required by the lmdb dataloader)
    np.savez(str(out_dir / "metadata.npz"),
             natoms=np.array(natoms_list, dtype=np.int32))

    logging.info(
        f"  Written {split_name}: {new_i} entries "
        f"({failed} failed) → {out_path}"
    )
    return new_i, natoms_list


# ─────────────────────────────────────────────────────────────────────────────
# Main
# ─────────────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--filter-stable", action="store_true",
                        help="Only keep structures with e_above_hull == 0")
    args = parser.parse_args()

    check_deps()

    if not CSV_GVRH.exists():
        print(f"ERROR: {CSV_GVRH} not found.\n"
              f"Run first:  MP_API_KEY=... python scripts/build_lmdb/download_bulk_modulus.py")
        sys.exit(1)

    logging.info("Loading bulk modulus data ...")
    bulk_mod = read_bulk_modulus(CSV_GVRH)
    logging.info(f"  {len(bulk_mod):,} materials with bulk modulus")

    records = read_main_csv(CSV_ALL, bulk_mod, args.filter_stable)
    logging.info(f"\nIntersection size: {len(records):,} structures")

    if len(records) == 0:
        print("ERROR: No common structures found. Check that download_bulk_modulus.py ran successfully.")
        sys.exit(1)

    # Shuffle and 80 / 10 / 10 split
    rng  = np.random.default_rng(SEED)
    idxs = rng.permutation(len(records))
    n    = len(records)
    n_tr = int(0.80 * n)
    n_va = int(0.10 * n)
    splits = {
        "train": idxs[:n_tr],
        "val":   idxs[n_tr:n_tr + n_va],
        "test":  idxs[n_tr + n_va:],
    }
    logging.info(
        f"Split: train={len(splits['train'])}, "
        f"val={len(splits['val'])}, test={len(splits['test'])}"
    )

    counts = {}
    all_natoms = {}
    for split_name, idx_arr in splits.items():
        n_written, nat = write_lmdb(records, records, idx_arr, split_name)
        counts[split_name] = n_written
        all_natoms[split_name] = nat

    # Compute normaliser statistics from training set
    tr_idx = splits["train"]
    stats = {}
    for pname, attr in [("eform", "eform"), ("bandgap", "bandgap"), ("gvrh", "gvrh")]:
        vals = np.array([records[i][attr] for i in tr_idx])
        stats[pname] = {
            "mean":  float(np.mean(vals)),
            "stdev": float(np.std(vals)),
            "min":   float(np.min(vals)),
            "max":   float(np.max(vals)),
        }

    # Print YAML block
    print("\n" + "="*65)
    print("Paste this into configs/mex-multi/mp20_three_property.yml:")
    print("="*65)
    print(f"""includes:
- configs/mex-multi/equiformer_v2/base_ebm_mp20_three_property.yml
- configs/mex-multi/params/base_param_multi.yml

dataset:
  property_names: [eform, bandgap, gvrh]""")
    for pname in ["eform", "bandgap", "gvrh"]:
        s = stats[pname]
        print(f"  train_max_y_{pname}: {s['max']}")
        print(f"  train_min_y_{pname}: {s['min']}")
    print("""
  train:
    format: lmdb
    src: data/mp20_three_property/train
    weighted_sample: false
    transforms:
      normalizer:""")
    for pname in ["eform", "bandgap", "gvrh"]:
        s = stats[pname]
        print(f"        y_{pname}:")
        print(f"          mean: {s['mean']}")
        print(f"          stdev: {s['stdev']}")
    print("""
  val:
    src: data/mp20_three_property/val
  test:
    src: data/mp20_three_property/test

logger: tensorboard""")
    print("="*65)
    print("\nDone.")


if __name__ == "__main__":
    main()
